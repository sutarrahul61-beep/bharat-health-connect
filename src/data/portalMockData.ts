// Default 11-stage treatment pathway helper
export function generateDefaultTimelineStages(currentStageIndex: number = 3): TreatmentTimelineStageInfo[] {
  const stageDefs: Array<{ id: TreatmentTimelineStageInfo['id']; label: string; description: string }> = [
    { id: 'NEW_PATIENT', label: 'New Patient', description: 'Patient registered and initial medical query received by Bharat Health Connect coordinator desk.' },
    { id: 'DOCUMENTS_RECEIVED', label: 'Documents Received', description: 'All clinical reports, imaging, pathology scans, and medical history documents successfully collected.' },
    { id: 'HOSPITAL_REVIEW', label: 'Hospital Review', description: 'Assigned specialist panel and head surgeon reviewing patient case and formulating treatment pathway.' },
    { id: 'COST_ESTIMATE', label: 'Cost Estimate', description: 'Detailed hospital quotation, treatment duration, and package cost prepared and verified.' },
    { id: 'APPOINTMENT', label: 'Appointment Scheduled', description: 'Pre-admission consultation or hospital arrival slot scheduled with lead specialist.' },
    { id: 'VISA', label: 'Visa & Travel Documents', description: 'Official Medical Visa Invitation letter issued and Indian Embassy processing assisted.' },
    { id: 'TRAVEL', label: 'Travel & Reception', description: 'Flight itinerary confirmed, airport escort at Goa/Belagavi/Pune arranged to Miraj.' },
    { id: 'ADMISSION', label: 'Hospital Admission', description: 'Patient registered in hospital, pre-operative investigations and room allocation initiated.' },
    { id: 'TREATMENT', label: 'Treatment / Surgery', description: 'Main clinical procedure, surgical intervention, or scheduled therapy conducted by senior team.' },
    { id: 'DISCHARGE', label: 'Discharge & Recovery', description: 'Successful clinical recovery, discharge summary, medicine supply, and local stay recovery monitoring.' },
    { id: 'FOLLOW_UP', label: 'Follow-Up & Telehealth', description: 'Post-treatment tele-consultation, long-term recovery checklist, and digital records archival.' },
  ];

  return stageDefs.map((def, idx) => {
    let status: 'completed' | 'current' | 'upcoming' = 'upcoming';
    let completedDate: string | undefined = undefined;

    if (idx < currentStageIndex) {
      status = 'completed';
      completedDate = `2026-09-${12 + idx} 14:00`;
    } else if (idx === currentStageIndex) {
      status = 'current';
    }

    return {
      id: def.id,
      label: def.label,
      stepNumber: idx + 1,
      description: def.description,
      status,
      completedDate,
      notes: idx === currentStageIndex ? 'Currently in progress. Case coordinator is actively managing this step.' : undefined,
    };
  });
}

